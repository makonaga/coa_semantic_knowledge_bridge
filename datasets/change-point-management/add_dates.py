FIELDS = ["id", "機種名", "変更日", "変更内容", "変更内容詳細", "評価内容", "評価内容詳細", "評価結果"]


def main() -> None:
    with open("change_points.json", encoding="utf-8") as f:
        data = json.load(f)

    assert set(DATES) == {r["id"] for r in data}, "date map does not cover all ids"
    for before, after in ORDER_CONSTRAINTS:
        assert DATES[before] < DATES[after], f"order violation: {before} !< {after}"

    out = []
    for r in data:
        r["変更日"] = DATES[r["id"]]
        out.append({k: r[k] for k in FIELDS})

    with open("change_points.json", "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write("\n")

    with open("change_points.csv", "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(out)

    years = sorted({d[:4] for d in DATES.values()})
    print(f"OK: 100 records dated, years {years[0]}-{years[-1]}, "
          f"{len(ORDER_CONSTRAINTS)} order constraints satisfied")


if __name__ == "__main__":
    main()
